CREATE TABLE bookings (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id      INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  availability_id INTEGER NOT NULL REFERENCES availability(id) ON DELETE CASCADE,
  status          TEXT NOT NULL DEFAULT 'CONFIRMED'
                  CHECK (status IN ('CONFIRMED', 'CANCELLED')),
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  cancelled_at    TIMESTAMPTZ
);

-- Un horario solo puede tener UNA reserva activa
CREATE UNIQUE INDEX uq_bookings_active_slot
  ON bookings (availability_id) WHERE status = 'CONFIRMED';

CREATE INDEX idx_bookings_student ON bookings (student_id, status);