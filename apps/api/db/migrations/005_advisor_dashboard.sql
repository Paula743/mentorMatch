-- Panel del tutor: perfil, materias (etiquetas), horarios semanales,
-- materia por sesión, calificaciones y propuestas para reagendar.

-- Materias: el nombre es único sin importar mayúsculas ("Cálculo" = "cálculo")
CREATE TABLE subjects (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       VARCHAR(60) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uq_subjects_name ON subjects (lower(name));

-- Perfil que ven los alumnos
CREATE TABLE advisor_profiles (
  user_id             INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  bio                 TEXT NOT NULL,
  career_name         VARCHAR(120) NOT NULL,
  semesters_completed SMALLINT NOT NULL CHECK (semesters_completed >= 0),
  semesters_total     SMALLINT NOT NULL CHECK (semesters_total BETWEEN 1 AND 20),
  updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (semesters_completed <= semesters_total)
);

-- Materias que ofrece cada tutor
CREATE TABLE advisor_subjects (
  user_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  subject_id INTEGER NOT NULL REFERENCES subjects(id) ON DELETE CASCADE,
  PRIMARY KEY (user_id, subject_id)
);

-- Plantilla semanal: cada fila es una hora que se repite todas las semanas
CREATE TABLE weekly_hours (
  tutor_id INTEGER  NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  weekday  SMALLINT NOT NULL CHECK (weekday BETWEEN 1 AND 7),
  hour     SMALLINT NOT NULL CHECK (hour BETWEEN 0 AND 23),
  PRIMARY KEY (tutor_id, weekday, hour)
);

-- Los horarios generados se cierran en lugar de borrarse, para no perder historial
ALTER TABLE availability ADD COLUMN is_active BOOLEAN NOT NULL DEFAULT true;

-- Materia con la que se agendó la sesión
ALTER TABLE bookings ADD COLUMN subject_id INTEGER REFERENCES subjects(id) ON DELETE SET NULL;

-- Calificación y comentario del alumno sobre una sesión ya impartida
CREATE TABLE session_reviews (
  booking_id INTEGER PRIMARY KEY REFERENCES bookings(id) ON DELETE CASCADE,
  rating     SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 5),
  comment    VARCHAR(600),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- El tutor propone otro horario, el alumno decide
CREATE TABLE reschedule_proposals (
  id                       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id               INTEGER NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
  proposed_availability_id INTEGER NOT NULL REFERENCES availability(id) ON DELETE CASCADE,
  message                  VARCHAR(300),
  status                   TEXT NOT NULL DEFAULT 'PENDING'
                           CHECK (status IN ('PENDING', 'ACCEPTED', 'REJECTED', 'CANCELLED')),
  created_at               TIMESTAMPTZ NOT NULL DEFAULT now(),
  responded_at             TIMESTAMPTZ
);

-- Solo una propuesta pendiente por sesión
CREATE UNIQUE INDEX uq_proposal_pending ON reschedule_proposals (booking_id) WHERE status = 'PENDING';
CREATE INDEX idx_availability_tutor_start ON availability (tutor_id, starts_at);
